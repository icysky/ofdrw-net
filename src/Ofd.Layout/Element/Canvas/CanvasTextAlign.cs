namespace Ofd.Layout.Element.Canvas;

/// <summary>文本内容的对齐方式（Java canvas.TextAlign）。</summary>
public enum CanvasTextAlign
{
    /// <summary>文本在指定位置开始。</summary>
    Start,

    /// <summary>文本在指定位置结束。</summary>
    End,

    /// <summary>文本中心放在指定位置。</summary>
    Center,

    /// <summary>文本左对齐。</summary>
    Left,

    /// <summary>文本右对齐。</summary>
    Right,
}
